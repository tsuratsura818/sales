# ── 応答の後処理 ────────────────────────────────────────────
# ChatGPT はウェブ検索を使うと、本文に引用マークを差し込む。
# UI からテキストを取り出す方式のため、これが本文に混ざって届く。
#   例:  …気になりました。
#        Yahoo!ショッピング
#        +1
# プロンプトで「付けるな」と言っても UI 側が付けるものなので、
# 取得後にこちらで落とす。
import re  # noqa: E402

# 単独行に出る出典名（サイト名だけの行）と「+N」形式の追加件数表示
_CITATION_LINE = re.compile(
    r"^[ \t　]*(?:\+\d+|Yahoo!?ショッピング|楽天市場|楽天|Amazon|amazon\.co\.jp|"
    r"[A-Za-z0-9.\-]+\.(?:com|jp|co\.jp|net|org)|出典|参考)[ \t　]*$",
    re.MULTILINE,
)


def strip_citations(text: str) -> str:
    """ChatGPTの引用マーク（出典名の行・+N）を本文から取り除く"""
    if not text:
        return text
    t = _CITATION_LINE.sub("", text)
    # 文中に紛れ込む [1] 形式の脚注番号も落とす
    t = re.sub(r"[（(]?\s*\[\d+\]\s*[）)]?", "", t)
    # 除去で空行が増えるので、3行以上の連続改行は2行に詰める
    t = re.sub(r"\n{3,}", "\n\n", t)
    return t.strip()


def clean_generated(items: list[dict]) -> list[dict]:
    """生成結果の件名・本文から引用マークを除去する"""
    out = []
    for it in items:
        out.append({
            **it,
            "subject": strip_citations(it.get("subject", "")).replace("\n", " ").strip(),
            "body": strip_citations(it.get("body", "")),
        })
    return out


# ── ChatGPT 呼び出し ────────────────────────────────────────
# 常時起動のChrome(CDP)を画像生成ジョブ等と共有しているため、
# 実行が重なるとロックを取れない。ask.mjs の既定待ち時間は300秒で、
# 画像生成が長引くとその日の送信が空振りする。日次送信は時刻に厳密で
# ないので、待ち時間を長く取って確実に通す。
CHROME_LOCK_WAIT_MS = 45 * 60 * 1000   # 45分待つ
ASK_TIMEOUT_MS = 15 * 60 * 1000        # 生成自体の上限（実測 142〜435秒）

CHATGPT_DIR = "/Users/nishikawamasashi/chatgpt-image-auto"


def ask_chatgpt(prompt: str) -> str:
    """ログイン済みChatGPTに投げて応答テキストを返す（Claudeの枠を使わない）"""
    import json as _json
    import subprocess
    import tempfile

    with tempfile.NamedTemporaryFile("w", suffix=".txt", delete=False, encoding="utf-8") as f:
        f.write(prompt)
        path = f.name

    env = {**os.environ, "LOCK_WAIT_MS": str(CHROME_LOCK_WAIT_MS)}
    r = subprocess.run(
        ["node", "ask.mjs", "--file", path, "--json", "--timeout", str(ASK_TIMEOUT_MS)],
        cwd=CHATGPT_DIR, capture_output=True, env=env,
        timeout=(CHROME_LOCK_WAIT_MS + ASK_TIMEOUT_MS) / 1000 + 120,
    )
    if r.returncode != 0:
        raise RuntimeError(
            "ChatGPT呼び出しに失敗: " + r.stderr.decode("utf-8", "replace")[-300:]
        )
    d = _json.loads(r.stdout.decode("utf-8", "replace"))
    if not d.get("ok"):
        raise RuntimeError("ChatGPTの応答が失敗しました")
    return d.get("text", "")

